async function migratePlans() {
  const results = [];

  for (const item of plans) {
    try {
      const res = await fetch(`/api/subscription/admin/plans/${item.id}`, {
        method: "PUT",
        credentials: "include",
        headers: {
          accept: "application/json, text/plain, */*",
          "content-type": "application/json",
          "new-api-user": "1",
        },
        body: JSON.stringify({ plan: item.plan }),
      });

      const data = await res.json().catch(() => ({}));
      results.push({
        id: item.id,
        title: item.plan.title,
        ok: res.ok && data.success !== false,
        status: res.status,
        data,
      });

      console.log(
        `[${res.ok ? "OK" : "FAIL"}]`,
        item.id,
        item.plan.title,
        res.status,
        data
      );
    } catch (error) {
      results.push({
        id: item.id,
        title: item.plan.title,
        ok: false,
        error: String(error),
        status: "",
      });

      console.error("[ERROR]", item.id, item.plan.title, error);
    }
  }

  console.table(
    results.map((item) => ({
      id: item.id,
      title: item.title,
      ok: item.ok,
      status: item.status ?? "",
      error: item.error ?? "",
    }))
  );

  return results;
}

migratePlans();
